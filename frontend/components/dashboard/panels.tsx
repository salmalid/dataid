function headlineTiles(result: RunResult) {
  const metrics = result.metrics ?? {};
  const pairs: [string, keyof typeof metrics][] =
    result.task_type === "classification"
      ? [
          ["Accuracy", "accuracy"],
          ["F1", "f1"],
          ["Recall", "recall"],
          ["ROC AUC", "roc_auc"],
        ]
      : [
          ["R²", "r2"],
          ["MAE", "mae"],
          ["RMSE", "rmse"],
          ["MAPE", "mape"],
        ];

  return pairs
    .filter(([, key]) => typeof metrics[key] === "number")
    .map(([label, key]) => ({
      label,
      value: formatMetric(String(key), metrics[key] as number),
      caption: "holdout",
    }));
}

/* ================================================================== data quality */
export function DataPanel({ result }: { result: RunResult }) {
  const issues = [...(result.issues ?? [])].sort(
    (a, b) =>
      ["critical", "warning", "info"].indexOf(a.severity) -
      ["critical", "warning", "info"].indexOf(b.severity),
  );
  const counts = {
    critical: issues.filter((i) => i.severity === "critical").length,
    warning: issues.filter((i) => i.severity === "warning").length,
    info: issues.filter((i) => i.severity === "info").length,
  };

  const missing = result.eda?.missing_by_column ?? [];
  const balance = result.eda?.class_balance ?? [];
  const matrix = result.eda?.correlation_matrix;
  const cleaning = result.cleaning_summary;

  return (
    <div className="space-y-6">
      <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-4">
        <StatTile
          label="Critical findings"
          value={counts.critical}
          caption="block release"
          tone={counts.critical ? "critical" : undefined}
        />
        <StatTile label="Warnings" value={counts.warning} caption="handled automatically" />
        <StatTile
          label="Rows removed"
          value={formatNumber(cleaning?.rows_removed ?? 0)}
          caption="duplicates and null targets"
        />
        <StatTile
          label="Columns dropped"
          value={cleaning?.columns_removed ?? 0}
          caption="identifiers, constants, leakage"
        />
      </div>

      <Card>
        <CardHeader
          title="Detective findings"
          subtitle="Everything the profiler flagged, most severe first."
        />
        <div className="mt-4">
          <DataTable
            columns={[
              {
                key: "severity",
                header: "Severity",
                render: (row) => (
                  <Badge
                    tone={severityTone(String(row.severity))}
                    icon={
                      row.severity === "critical" ? (
                        <IconAlert className="h-3 w-3" />
                      ) : row.severity === "info" ? (
                        <IconCheck className="h-3 w-3" />
                      ) : undefined
                    }
                  >
                    {String(row.severity)}
                  </Badge>
                ),
              },
              { key: "category", header: "Category", render: (row) => titleCase(String(row.category)) },
              {
                key: "column",
                header: "Column",
                render: (row) => (
                  <code className="rounded bg-black/[0.05] px-1.5 py-0.5 text-[11.5px] dark:bg-white/[0.07]">
                    {String(row.column ?? "—")}
                  </code>
                ),
              },
              { key: "message", header: "Finding" },
            ]}
            rows={issues as unknown as Record<string, unknown>[]}
            emptyMessage="No issues detected — unusually clean data."
          />
        </div>
      </Card>

      <Card className="p-5">
        <h3 className="text-[15px] font-semibold">Cleaning actions applied</h3>
        <ul className="mt-4 space-y-2.5">
          {(cleaning?.actions ?? []).map((action, index) => (
            <li key={index} className="flex gap-3 text-[13px]">
              <Badge tone="brand" className="shrink-0">
                {titleCase(action.action)}
              </Badge>
              <span className="text-secondary">{action.detail}</span>
            </li>
          ))}
          {!cleaning?.actions?.length && (
            <li className="text-[13px] text-muted">No changes were required.</li>
          )}
        </ul>
      </Card>

      <div className="grid gap-5 lg:grid-cols-2">
        {missing.length > 0 && (
          <BarChart
            data={missing.map((entry) => ({ label: entry.column, value: entry.pct }))}
            title="Missing values"
            subtitle="Percent null per column, before imputation"
            unit="%"
            color="var(--status-warning)"
            formatValue={(value) => value.toFixed(2)}
          />
        )}
        {balance.length > 0 && (
          <BarChart
            data={balance.map((entry) => ({ label: entry.label, value: entry.count }))}
            title="Class balance"
            subtitle="Rows per target class"
            color={seriesVar(2)}
            formatValue={(value) => formatNumber(value)}
          />
        )}
        {matrix && matrix.columns.length > 1 && (
          <Heatmap
            columns={matrix.columns}
            values={matrix.values}
            title="Feature correlation"
            subtitle="Blue negative · gray none · red positive"
            className="lg:col-span-2"
          />
        )}
      </div>

      <FeaturePanel result={result} />
    </div>
  );
}

