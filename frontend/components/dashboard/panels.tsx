/* ================================================================== models */
export function ModelsPanel({ result }: { result: RunResult }) {
  const leaderboard = useMemo(() => result.leaderboard ?? [], [result.leaderboard]);
  const primary = result.research?.primary_metric ?? "accuracy";
  const metricKey = leaderboard.length && primary in leaderboard[0] ? primary : "accuracy";

  const metricColumns = useMemo(() => {
    if (!leaderboard.length) return [];
    const candidates = [
      "roc_auc", "pr_auc", "accuracy", "f1", "precision", "recall",
      "r2", "rmse", "mae", "mape", "cv_mean", "overfit_gap", "fit_seconds",
    ];
    return candidates.filter((key) => key in leaderboard[0]);
  }, [leaderboard]);

  if (!leaderboard.length) {
    return <EmptyState title="No leaderboard" description="This run produced no trained models." />;
  }

  return (
    <div className="space-y-6">
      <BarChart
        data={leaderboard.slice(0, 14).map((row) => ({
          label: String(row.model),
          value: Number(row[metricKey] ?? 0),
        }))}
        title="Leaderboard"
        subtitle={`Holdout ${metricKey} · ${leaderboard.length} models trained on the same split`}
        max={14}
        formatValue={(value) => value.toFixed(4)}
      />

      <Card>
        <CardHeader
          title="All candidates"
          subtitle="Same preprocessor, same holdout — differences are the models, not the plumbing."
        />
        <div className="mt-4">
          <DataTable
            highlightFirst
            columns={[
              { key: "rank", header: "#", align: "right" },
              { key: "model", header: "Model" },
              { key: "family", header: "Family", render: (row) => titleCase(String(row.family)) },
              ...metricColumns.map((key) => ({
                key,
                header: key === "fit_seconds" ? "fit (s)" : key.replace(/_/g, " "),
                align: "right" as const,
                render: (row: Record<string, unknown>) =>
                  row[key] === null || row[key] === undefined
                    ? "—"
                    : formatMetric(key, Number(row[key])),
              })),
            ]}
            rows={leaderboard as unknown as Record<string, unknown>[]}
          />
        </div>
      </Card>

      <div className="grid gap-5 lg:grid-cols-2">
        <MetricCharts result={result} />
      </div>
    </div>
  );
}

