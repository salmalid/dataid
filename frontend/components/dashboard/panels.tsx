/** The documents a run produced. Presented where people land, not buried under Deploy. */
export function OutputsCard({
  result,
  runId,
  only,
}: {
  result: RunResult;
  runId: string;
  only?: string[];
}) {
  const entries = Object.keys(result.artifacts ?? {}).filter(
    (key) => !only || only.includes(key),
  );
  if (entries.length === 0) return null;

  return (
    <Card>
      <CardHeader
        title="Your outputs"
        subtitle="Generated by this run. Pick what gets built on the run form."
      />
      <div className="grid gap-3 p-5 pt-4 sm:grid-cols-2">
        {entries.map((key) => {
          const meta = ARTIFACT_META[key] ?? { label: key, hint: "" };
          const href = `/api/runs/${runId}/artifacts/${key}`;
          return (
            <div
              key={key}
              className="flex items-start gap-3 rounded-xl border p-3.5"
            >
              <IconFile className="mt-0.5 h-4 w-4 shrink-0 text-muted" />
              <div className="min-w-0 flex-1">
                <p className="text-[13px] font-medium">{meta.label}</p>
                <p className="mt-0.5 text-[12px] text-secondary">{meta.hint}</p>
                <div className="mt-2.5 flex flex-wrap gap-2">
                  {meta.viewable && (
                    <a
                      href={`${href}?inline=true`}
                      target="_blank"
                      rel="noreferrer"
                      className="inline-flex h-7 items-center gap-1.5 rounded-lg border px-2.5 text-[12px] transition-colors hover:bg-black/[0.04] dark:hover:bg-white/[0.06]"
                    >
                      <IconEye className="h-3.5 w-3.5" />
                      Open
                    </a>
                  )}
                  <a
                    href={href}
                    download
                    className="inline-flex h-7 items-center gap-1.5 rounded-lg border px-2.5 text-[12px] transition-colors hover:bg-black/[0.04] dark:hover:bg-white/[0.06]"
                  >
                    <IconDownload className="h-3.5 w-3.5" />
                    Download
                  </a>
                </div>
              </div>
            </div>
          );
        })}
      </div>
    </Card>
  );
}

